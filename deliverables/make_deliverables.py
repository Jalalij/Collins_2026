"""Assemble a dated snapshot of the deliverables (paper, report, supplementary docs).

    python3 deliverables/make_deliverables.py 2026-11-07_final

Creates deliverables/<stamp>/ with the compiled PDFs, Overleaf-ready source zips of the paper and
the report, the supplementary docs, and a number audit that maps every generated number of the
paper to its result file. The live sources stay in paper_twc/ and reports/final_report/. Earlier
snapshots (archive/, older deliverables/<stamp>/) are never modified.
"""
import json
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def zip_tree(src: Path, dst: Path, skip=(".log", ".aux", ".out", ".blg", ".toc", ".synctex.gz")):
    with zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(src.rglob("*")):
            if f.is_file() and not f.name.startswith((".", "zz_", "_fig_")) and not f.name.endswith(skip):
                z.write(f, f.relative_to(src))


def main():
    stamp = sys.argv[1] if len(sys.argv) > 1 else "snapshot"
    out = ROOT / "deliverables" / stamp
    if out.exists():
        shutil.rmtree(out)
    (out / "docs").mkdir(parents=True)
    paper, report = ROOT / "paper_twc", ROOT / "reports/final_report"
    shutil.copy(paper / "main.pdf", out / f"TWC_paper_{stamp}.pdf")
    shutil.copy(report / "main.pdf", out / f"Final_report_{stamp}.pdf")
    zip_tree(paper, out / f"TWC_paper_source_{stamp}.zip")
    zip_tree(report, out / f"Final_report_source_{stamp}.zip")
    for f in ["CHANGES.md", "DATA_AUDIT.md", "REPRODUCE.md"]:
        shutil.copy(ROOT / "docs/final_report" / f, out / "docs" / f)
    # number audit of the paper
    pn = json.load(open(ROOT / "modeling/results_final/analysis/paper_numbers.json"))
    lines = ["# Number audit of the TWC paper", "",
             "Every macro below is written by `modeling/experiments/fr_paper_numbers.py` into "
             "`paper_twc/figs/data/numbers_story.tex`. The source column names the result file the value is read from. "
             "The older macros (`numbers_audit.tex`, `numbers_results.tex`, `numbers_analysis.tex`) are written by "
             "`final_audit_numbers.py` and `final_tables.py` from `modeling/results_final/summary/`.", "",
             "| Macro | Value | Source |", "|---|---|---|"]
    for k, v in pn.items():
        val = v["value"].replace("$-$", "-").replace("$+$", "+").replace("|", "/")
        lines.append(f"| `\\{k}` | {val} | {v['source'].replace('|', '/')} |")
    (out / "docs/PAPER_NUMBER_AUDIT.md").write_text("\n".join(lines) + "\n")
    (out / "README.md").write_text(README.format(stamp=stamp))
    print("written", out)


