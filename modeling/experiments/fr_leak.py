"""
experiments/fr_leak.py - What the Starlink interpolation leak does to a trained model.

For Starlink DL RTT, per horizon step (seed means over 3 seeds):
  A  trained on interpolated inputs, tested on interpolated inputs  (what one would report)
  B  trained on interpolated inputs, tested on causal inputs        (what one gets in deployment)
  C  trained on causal inputs,       tested on causal inputs        (this study)
for S2S (prev_seq2seq) and DS2S (fr_dist), plus persistence on both input versions.

Reads  results_final/leak/starlink_dl/<m>_s<k>.csv, <m>_s<k>_causaltest.csv,
       results_final/main/starlink_dl/<m>_s<k>.csv, results_final/audit/{legacy,causal}/starlink_dl/persistence_s0.csv
Writes results_final/analysis/leak/leak_horizon.csv, leak_summary.json,
       <report>/data/fr_leak_<m>.dat, <report>/figs/fr_leak.tex
"""
import argparse, json
from pathlib import Path
import numpy as np, pandas as pd

ROOT = Path(__file__).resolve().parent.parent


def load(paths, col):
    ds = [pd.read_csv(p) for p in paths if Path(p).exists()]
    if not ds:
        return None, 0
    d = pd.concat(ds)
    d = d[d.target == "rtt"]
    return d.groupby("h")[col].mean(), len(ds)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", default=str(ROOT.parent / "reports/final_report"))
    a = ap.parse_args()
    rep = Path(a.report)
    out = ROOT / "results_final/analysis/leak"; out.mkdir(parents=True, exist_ok=True)
    L = ROOT / "results_final/leak/starlink_dl"; M = ROOT / "results_final/main/starlink_dl"
    rows, summ = [], {}
    for m, nm in [("prev_seq2seq", "S2S"), ("fr_dist", "DS2S")]:
        for metric, col in [("RMSE", "RMSE"), ("MAE", "MAE_median" if m == "fr_dist" else "MAE")]:
            A, na = load([L / f"{m}_s{k}.csv" for k in range(3)], col)
            B, nb = load([L / f"{m}_s{k}_causaltest.csv" for k in range(3)], col)
            C, nc = load([M / f"{m}_s{k}.csv" for k in range(3)], col)
            if A is None or B is None or C is None:
                continue
            for h in A.index:
                rows.append({"model": nm, "metric": metric, "h": h, "A_leak_leak": A[h], "B_leak_causal": B[h], "C_causal_causal": C[h]})
            summ[f"{nm}_{metric}"] = {
                "n_seeds": [na, nb, nc],
                "optimism_h1_pct": 100 * (B[1] / A[1] - 1), "optimism_avg_pct": 100 * (B.mean() / A.mean() - 1),
                "deploy_penalty_vs_causal_h1_pct": 100 * (B[1] / C[1] - 1), "deploy_penalty_vs_causal_avg_pct": 100 * (B.mean() / C.mean() - 1),
                "reported_vs_true_h1_pct": 100 * (A[1] / C[1] - 1), "reported_vs_true_avg_pct": 100 * (A.mean() / C.mean() - 1),
                "A_avg": A.mean(), "B_avg": B.mean(), "C_avg": C.mean(), "A_h1": A[1], "B_h1": B[1], "C_h1": C[1]}
    pl = pd.read_csv(ROOT / "results_final/audit/legacy/starlink_dl/persistence_s0.csv"); pc = pd.read_csv(ROOT / "results_final/audit/causal/starlink_dl/persistence_s0.csv")
    pl, pc = pl[pl.target == "rtt"].set_index("h").RMSE, pc[pc.target == "rtt"].set_index("h").RMSE
    summ["persistence_RMSE"] = {"leaky_h1": pl[1], "causal_h1": pc[1], "increase_h1_pct": 100 * (pc[1] / pl[1] - 1),
                                "leaky_avg": pl.mean(), "causal_avg": pc.mean()}
    df = pd.DataFrame(rows); df.to_csv(out / "leak_horizon.csv", index=False)
    json.dump(summ, open(out / "leak_summary.json", "w"), indent=1)
    print(json.dumps(summ, indent=1))
    for nm in ["S2S", "DS2S"]:
        w = df[(df.model == nm) & (df.metric == "RMSE")][["h", "A_leak_leak", "B_leak_causal", "C_causal_causal"]].copy()
        w["t"] = w.h * 0.2
        w["pers_leak"] = pl.values; w["pers_causal"] = pc.values
        w.to_csv(rep / f"data/fr_leak_{nm}.dat", sep=" ", index=False, float_format="%.4f")
    # figure (one column): DS2S RTT MAE vs horizon for A/B/C, inset zoom on the first 0.6 s
    f = "data/fr_leak_DS2S_MAE.dat"
    w = df[(df.model == "DS2S") & (df.metric == "MAE")][["h", "A_leak_leak", "B_leak_causal", "C_causal_causal"]].copy()
    w["t"] = w.h * 0.2
    w.to_csv(rep / f, sep=" ", index=False, float_format="%.4f")
    cols = ["A_leak_leak", "B_leak_causal", "C_causal_causal"]
    first = w[w.t <= 0.61]
    lo, hi = float(first[cols].min().min()), float(first[cols].max().max())
    pad = 0.12 * (hi - lo); lo -= pad; hi += pad
    ymin = float(np.floor(w[cols].min().min() - 1)); ymax = float(np.ceil(w[cols].max().max() + 1))
    fig = [r"% fr_leak.tex - generated by modeling/experiments/fr_leak.py, do not edit by hand.",
           r"\begin{tikzpicture}",
           rf"\begin{{axis}}[frbase, name=main, width=8.7cm, height=5.4cm, xmin=0.2, xmax=3, xtick={{0.2,1,2,3}}, ymin={ymin:.0f}, ymax={ymax:.0f},",
           r"  xlabel={horizon (s)}, ylabel={DS2S RTT MAE (ms), Starlink DL}, legend cell align=left,",
           r"  legend style={at={(0.5,1.03)}, anchor=south, legend columns=1, font=\scriptsize, draw=none}]",
           rf"\addplot[cPrev, thick, mark=o, mark size=1.2pt] table[x=t, y=A_leak_leak] {{{f}}}; \addlegendentry{{interpolated train and test (reported)}}",
           rf"\addplot[cResid, thick, dashed, mark=triangle*, mark size=1.3pt] table[x=t, y=B_leak_causal] {{{f}}}; \addlegendentry{{interpolated train, causal test (deployed)}}",
           rf"\addplot[cFR, very thick, mark=square*, mark size=1.1pt] table[x=t, y=C_causal_causal] {{{f}}}; \addlegendentry{{causal train and test (this paper)}}",
           rf"\draw[black!70] (axis cs:0.2,{lo:.4g}) rectangle (axis cs:0.6,{hi:.4g});",
           rf"\coordinate (lz) at (axis cs:0.6,{(lo + hi) / 2:.4g});",
           r"\end{axis}",
           rf"\begin{{axis}}[at={{($(main.south east)+(-0.2cm,0.5cm)$)}}, anchor=south east, width=3.4cm, height=2.6cm, xmin=0.2, xmax=0.6,",
           rf"  ymin={lo:.4g}, ymax={hi:.4g}, xtick={{0.2,0.4,0.6}}, tick label style={{font=\tiny}}, axis background/.style={{fill=white}}, grid=major, grid style={{gray!20}}, name=ins]",
           rf"\addplot[cPrev, thick, mark=o, mark size=1pt] table[x=t, y=A_leak_leak] {{{f}}};",
           rf"\addplot[cResid, thick, dashed, mark=triangle*, mark size=1pt] table[x=t, y=B_leak_causal] {{{f}}};",
           rf"\addplot[cFR, very thick, mark=square*, mark size=1pt] table[x=t, y=C_causal_causal] {{{f}}};",
           r"\end{axis}",
           r"\draw[->, black!70] (lz) -- (ins.west);",
           r"\end{tikzpicture}"]
    (rep / "figs/fr_leak.tex").write_text("\n".join(fig) + "\n")


if __name__ == "__main__":
    main()
