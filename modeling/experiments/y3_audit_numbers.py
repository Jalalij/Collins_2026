"""
experiments/y3_audit_numbers.py - Macros for the audit section (Year 2
reproduction on the original data, effect of the Starlink ping fix, parameter
counts). Reads results_y3/explore (Year 2 data as-is, seed 0) and
results_y3/audit (persistence with and without the causal ping fix).
Writes reports/year3/data/numbers_audit.tex.
"""
import json, re
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT.parent / "reports/year3/data/numbers_audit.tex"
m = {}
ow = pd.read_csv(ROOT / "results_y3/explore/oneweb_dl/y2_seq2seq_s0.csv")
m["ReproOWMAE"], m["ReproOWRMSE"], m["ReproOWRtwo"] = f"{ow.MAE.mean():.2f}", f"{ow.RMSE.mean():.2f}", f"{ow.R2.mean():.3f}"
txt = (ROOT / "results_y3/explore/starlink_dl/log.txt").read_text()
a = re.findall(r"=== starlink dl \| y2_seq2seq.*?AGG MAE=([\d.]+) RMSE=([\d.]+) R2=([\d.]+)", txt, re.S)[0]
m["ReproSLMAE"], m["ReproSLRMSE"], m["ReproSLRtwo"] = f"{float(a[0]):.2f}", f"{float(a[1]):.2f}", f"{float(a[2]):.3f}"
c = pd.read_csv(ROOT / "results_y3/audit/causal/starlink_dl/persistence_s0.csv")
l = pd.read_csv(ROOT / "results_y3/audit/legacy/starlink_dl/persistence_s0.csv")
r = lambda d, h: d[(d.target == "rtt") & (d.h == h)].RMSE.iloc[0]
m["AuditPersLegacyHone"], m["AuditPersCausalHone"] = f"{r(l, 1):.1f}", f"{r(c, 1):.1f}"
m["AuditPersLegacyAvg"] = f"{l[l.target == 'rtt'].RMSE.mean():.1f}"
m["AuditPersCausalAvg"] = f"{c[c.target == 'rtt'].RMSE.mean():.1f}"
m["AuditPersHonePct"] = f"{100 * (r(c, 1) / r(l, 1) - 1):.1f}"
j1 = json.load(open(ROOT / "results_y3/main/oneweb_dl/y3_dist_s0.json"))
j2 = json.load(open(ROOT / "results_y3/main/oneweb_dl/y3_resid_s0.json"))
j3 = json.load(open(ROOT / "results_y3/main/oneweb_dl/y2_seq2seq_s0.json"))
fmt = lambda v: f"{v:,}".replace(",", "{,}")
m["ParamsDist"], m["ParamsResid"], m["ParamsYtwo"] = fmt(j1["params"]), fmt(j2["params"]), fmt(j3["params"])
lines = ["% Generated by modeling/experiments/y3_audit_numbers.py. Do not edit."]
lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
OUT.write_text("\n".join(lines) + "\n")
print(OUT.read_text())
